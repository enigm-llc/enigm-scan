export function findingLabel(category: string, language: Language) {
  if (labels[category]) return labels[category][language];
  if (category.startsWith("MVT ")) {
    const module = category.slice(4);
    return `MVT · ${moduleLabel(module, language) ?? module}`;
  }
  return category;
}

