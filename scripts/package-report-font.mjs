// Reproducible PDF-only module; the font is not fetched at runtime.
import fs from "node:fs";
import { createHash } from "node:crypto";
import { jsPDF } from "jspdf";
const data = fs.readFileSync(
  new URL("../assets/fonts/Roboto-Regular.ttf", import.meta.url),
);
if (
  createHash("sha256").update(data).digest("hex") !==
  "9f300202f482ad59f8b13bc3131a295744d14fd530fa3765a0a11ec87264d203"
)
  throw Error("Unexpected font bytes");
const base64 = data.toString("base64"),
  pdf = new jsPDF();
pdf.addFileToVFS("Roboto.ttf", base64);
pdf.addFont("Roboto.ttf", "Roboto", "normal");
pdf.setFont("Roboto");
const points = Object.keys(pdf.getFont().metadata.cmap.unicode.codeMap)
  .map(Number)
  .filter((n) => pdf.getFont().metadata.cmap.unicode.codeMap[n] > 0)
  .sort((a, b) => a - b);
const ranges = [];
for (const n of points) {
  const last = ranges.at(-1);
  if (last && last[1] === n - 1) last[1] = n;
  else ranges.push([n, n]);
}
fs.writeFileSync(
  new URL("../src/core/report-font.ts", import.meta.url),
  "// Generated by scripts/package-report-font.mjs. Roboto 3.016, OFL-1.1.\nexport const reportFont = " +
    JSON.stringify(base64) +
    ";\nexport const fontRanges: readonly (readonly [number, number])[] = " +
    JSON.stringify(ranges) +
    ";\n",
);
